export function translateText(value, language = 'en') {
  if (language !== 'it') return value;
  const source = String(value);
  const match = source.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const core = match[2].replace(/\s+/g, ' ');
  const translated = italian[core] ?? patterns.reduce((result,[pattern,replace])=>result??(pattern.test(core)?core.replace(pattern,replace):null),null);
  return translated == null ? value : `${match[1]}${translated}${match[3]}`;
}

