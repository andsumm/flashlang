export function localize(root, language = 'en') {
  document.documentElement.lang = language;
  document.title = language === 'it' ? 'Flashlang — Impara e ricorda.' : 'Flashlang — Make it stick.';
  if (language !== 'it' || !root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest(userContent)) continue;
    node.nodeValue = translateText(node.nodeValue, language);
  }
  for (const element of [root, ...root.querySelectorAll('[aria-label],[placeholder],[title]')]) {
    for (const attr of ['aria-label','placeholder','title']) {
      if (element.hasAttribute?.(attr)) element.setAttribute(attr, translateText(element.getAttribute(attr), language));
    }
  }
}
